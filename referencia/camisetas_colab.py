def normalizar(nombre):

    if not nombre:
        return ""

    nombre = nombre.lower()

    quitar = [
        "fc",
        "cf",
        "club",
        "de fútbol",
        "de futbol",
        "afc",
        "sc",
        "ac",
        "rcd"
    ]

    for palabra in quitar:
        nombre = nombre.replace(f" {palabra}", "")
        nombre = nombre.replace(f"{palabra} ", "")

    return "".join(filter(str.isalnum, nombre))


def obtener_partidos_hoy():

    headers = {
        "X-Auth-Token": API_KEY
    }

    response = requests.get(
        "https://api.football-data.org/v4/matches",
        headers=headers
    )

    if response.status_code != 200:
        print("❌ Error conectando con la API")
        return []

    matches = response.json()["matches"]

    hoy = datetime.datetime.now(MADRID_TZ).date()

    relevantes = []

    for match in matches:

        fecha = datetime.datetime.fromisoformat(
            match["utcDate"].replace("Z", "+00:00")
        ).astimezone(MADRID_TZ)

        if fecha.date() != hoy:
            continue

        relevantes.append({
            "home": match["homeTeam"]["name"],
            "away": match["awayTeam"]["name"],
            "hora": fecha,
            "competition": match["competition"]["name"]
        })

    return relevantes


def seleccionar_camiseta():

    partidos = obtener_partidos_hoy()

    elegida = random.choices(
        camisetas,
        k=1
    )[0]

    return elegida, partidos


def mostrar_resultado(camiseta, partidos):

    print("\n👕 RECOMENDACIÓN DEL DÍA")
    print("━━━━━━━━━━━━━━━━━━━━━━")

    texto = f"{camiseta['Equipo']}"

    if camiseta["Modelo"]:
        texto += f" - {camiseta['Modelo']}"

    if camiseta["Jugador"]:
        texto += f" ({camiseta['Jugador']})"

    print(texto)

    print("\n⚽ PARTIDOS RELEVANTES HOY")
    print("━━━━━━━━━━━━━━━━━━━━━━")

    ahora = datetime.datetime.now(MADRID_TZ)
    partidos_filtrados = [p for p in partidos if (ahora - p["hora"]).total_seconds() / 3600 <= 2]

    if not partidos_filtrados:
        print("No hay partidos relevantes hoy o ya han terminado hace más de 2 horas.")

    for p in partidos_filtrados:

        hora = p["hora"].strftime("%H:%M")

        print(
            f"⚽ {p['home']} vs {p['away']}"
        )

        print(
            f"🕒 {hora}"
        )

        print(
            f"🏆 {p['competition']}"
        )

        print()


camiseta, partidos = seleccionar_camiseta()

